"""Reproducing pytest files: rendering, file names, conftest and writing."""

import subprocess
import sys
from pathlib import Path

import pytest

from didibreak.compare import Finding
from didibreak.harness import PROCESS_EXITED_TYPE, Case, Outcome
from didibreak.report.pytest_writer import (
    Subject,
    conftest_roots,
    file_names,
    no_test_reason,
    render_conftest,
    render_test_file,
    write_tests,
)

PHONE = "app/utils/phone.py::normalize_phone"
SUBJECT = Subject(PHONE, "app.utils.phone", "normalize_phone", Path("/repo"))


def returned(repr_text: str, value: dict[str, object] | None) -> Outcome:
    return Outcome("return", "builtins.str", repr_text, value)


def text_value(text: str) -> Outcome:
    return returned(repr(text), {"type": "str", "value": text})


def finding(
    before: Outcome | None,
    after: Outcome | None = None,
    case: Case | None = None,
    label: str = "unexpected",
    identifier: str = "30040f8bc543",
) -> Finding:
    return Finding(
        identifier,
        PHONE,
        case or Case(("'995 555 12 34 56'",), {}, "country code without plus"),
        before,
        after or text_value("+995995555123456"),
        "high",
        label,
        "not covered by intent",
    )


def render(*findings: Finding, subject: Subject = SUBJECT) -> str:
    return render_test_file(subject, findings, "0.1.0", "a1b2c3d")


def test_literal_return_value_is_asserted_with_equality() -> None:
    text = render(finding(text_value("+995555123456")))

    assert text.startswith(
        f"# Reproducing tests for {PHONE}.\n"
        "# Generated by didibreak 0.1.0 from base commit\n# a1b2c3d.\n"
    )
    assert "from app.utils.phone import normalize_phone\n" in text
    assert "import pytest" not in text
    assert "# Case: country code without plus\n" in text
    assert "# Label: unexpected (not covered by intent)\n" in text
    assert "def test_normalize_phone_30040f8bc543() -> None:\n" in text
    assert "    result = normalize_phone('995 555 12 34 56')\n" in text
    assert "    assert result == '+995555123456'\n" in text


def test_floats_use_approx_with_the_comparison_tolerance() -> None:
    before = Outcome(
        "return", "builtins.float", "0.1", {"type": "float", "value": "0.1"}
    )

    text = render(finding(before))

    assert "import pytest\n" in text
    assert "assert result == pytest.approx(0.1, rel=1e-9, abs=1e-12)" in text


def test_value_that_is_not_a_literal_is_checked_by_type() -> None:
    before = Outcome("return", "app.models.Point", "Point(x=1, y=2)", None)

    text = render(finding(before))

    assert "# Weak check" in text
    assert "assert _type_name(result) == 'app.models.Point'" in text
    assert "def _type_name(value: object) -> str:" in text


def test_truncated_repr_is_checked_by_type() -> None:
    long_text = "x" * 3000
    before = returned(repr(long_text)[:2000], {"type": "str", "value": long_text})

    assert "assert _type_name(result) == 'builtins.str'" in render(finding(before))


def test_builtin_exception_is_asserted_with_its_exact_type() -> None:
    before = Outcome("exception", "builtins.ValueError", "ValueError('x')", None, "x")

    text = render(finding(before))

    assert "    with pytest.raises(ValueError) as info:\n" in text
    assert "        normalize_phone('995 555 12 34 56')\n" in text
    assert "    assert type(info.value) is ValueError\n" in text


def test_other_exceptions_are_asserted_by_qualified_name() -> None:
    before = Outcome("exception", "app.errors.PhoneError", "PhoneError()", None, "")

    text = render(finding(before))

    assert "with pytest.raises(BaseException) as info:" in text
    assert "assert _type_name(info.value) == 'app.errors.PhoneError'" in text


def test_equal_values_of_different_types_also_compare_the_repr() -> None:
    before = Outcome("return", "builtins.int", "1", {"type": "int", "value": 1})
    after = Outcome("return", "builtins.bool", "True", {"type": "bool", "value": True})

    text = render(finding(before, after))

    assert "    assert result == 1\n    assert repr(result) == '1'\n" in text


def test_methods_import_the_class_and_keyword_arguments_are_passed() -> None:
    subject = Subject("app/phone.py::Phone.parse", "app.phone", "Phone.parse", Path())
    case = Case(("'555'",), {"strict": "True"})

    text = render(finding(text_value("x"), case=case), subject=subject)

    assert "from app.phone import Phone\n" in text
    assert "result = Phone.parse('555', strict=True)" in text
    assert "def test_Phone_parse_30040f8bc543()" in text
    assert "# Case:" not in text  # no rationale


def test_function_named_like_a_local_is_imported_under_an_alias() -> None:
    subject = Subject("app/r.py::result", "app.r", "result", Path())

    text = render(finding(text_value("x")), subject=subject)

    assert "from app.r import result as subject_result\n" in text
    assert "result = subject_result('995 555 12 34 56')" in text


def test_expected_findings_get_no_test(tmp_path: Path) -> None:
    expected = finding(text_value("x"), label="expected")

    written = write_tests(tmp_path, tmp_path / "out", [expected], "0.1.0", "a1b")

    assert no_test_reason(expected) == "expected change"
    assert written.files == ()
    assert written.findings[0].test_file is None
    assert written.not_written == ((f"{PHONE}('995 555 12 34 56')", "expected change"),)


@pytest.mark.parametrize(
    ("before", "reason"),
    [
        (None, "new function: no base behavior to assert"),
        (Outcome("timeout", "", ""), "the base version timed out"),
        (
            Outcome("exception", PROCESS_EXITED_TYPE, "<exited>"),
            "the base version ended the process",
        ),
        (text_value("x"), None),
    ],
)
def test_findings_without_a_base_outcome_get_no_test(
    before: Outcome | None, reason: str | None
) -> None:
    assert no_test_reason(finding(before)) == reason


def test_colliding_file_names_get_a_hash_of_the_function() -> None:
    first = Subject("a.py::parse", "a", "parse", Path())
    second = Subject("b.py::parse", "b", "parse", Path())
    single = Subject("c.py::C.load", "c", "C.load", Path())

    names = file_names([first, second, single])

    assert names["c.py::C.load"] == "test_C_load.py"
    assert names["a.py::parse"] != names["b.py::parse"]
    assert names["a.py::parse"].startswith("test_parse_")


def test_conftest_roots_round_trip() -> None:
    text = render_conftest(["../..", "../../src", "../.."])

    assert conftest_roots(text) == ("../..", "../../src")
    assert conftest_roots("no roots here") == ()


def test_generated_files_pass_ruff_with_its_default_rules(tmp_path: Path) -> None:
    # Run as a user would: from the repository root, where the checked
    # package exists, so ruff sees it as first-party code.
    write_module(tmp_path, "def normalize_phone(text):\n    return text\n")
    folder = tmp_path / ".didibreak" / "tests"
    folder.mkdir(parents=True)
    exception = Outcome("exception", "app.errors.E", "E()", None, "")
    point = Outcome("return", "app.models.Point", "Point()", None)
    (folder / "test_x.py").write_text(
        render(
            finding(text_value("x")),
            finding(exception, identifier="0a1b2c3d4e5f"),
            finding(point, identifier="5f4e3d2c1b0a"),
        )
    )
    (folder / "test_y.py").write_text(render(finding(text_value("x"))))
    (folder / "conftest.py").write_text(render_conftest(["../.."]))

    command = [sys.executable, "-m", "ruff", "check", "--isolated", "--no-cache"]
    result = subprocess.run(
        [*command, "--extend-select", "W", ".didibreak/tests"],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        check=False,
    )

    assert result.returncode == 0, result.stdout


def write_module(root: Path, source: str) -> None:
    folder = root / "app" / "utils"
    folder.mkdir(parents=True)
    (folder / "phone.py").write_text(source, encoding="utf-8")


def test_written_tests_pass_on_the_base_and_fail_after_the_change(
    tmp_path: Path,
) -> None:
    base = "def normalize_phone(text):\n    return '+' + text.replace(' ', '')[-12:]\n"
    write_module(tmp_path, base)
    output_dir = tmp_path / ".didibreak"

    written = write_tests(
        tmp_path, output_dir, [finding(text_value("+995555123456"))], "0.1.0", "a1b"
    )

    assert written.files == (".didibreak/tests/test_normalize_phone.py",)
    assert written.findings[0].test_file == written.files[0]
    assert (output_dir / ".gitignore").read_text().endswith("*\n")
    pytest_command = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"]
    tests = str(output_dir / "tests")
    run = subprocess.run([*pytest_command, tests], cwd=tmp_path, check=False)
    assert run.returncode == 0
    changed = "def normalize_phone(text):\n    return '+995' + text.replace(' ', '')\n"
    (tmp_path / "app" / "utils" / "phone.py").write_text(changed)
    run = subprocess.run([*pytest_command, tests], cwd=tmp_path, check=False)
    assert run.returncode == 1


def test_new_functions_and_base_timeouts_are_listed_without_a_test(
    tmp_path: Path,
) -> None:
    new = finding(None, label="new_function")
    timeout = finding(Outcome("timeout", "", ""))

    written = write_tests(tmp_path, tmp_path / "out", [new, timeout], "0.1.0", "a1b")

    assert written.files == ()
    assert [f.test_file for f in written.findings] == [None, None]
    assert written.not_written == (
        (f"{PHONE}('995 555 12 34 56')", "new function: no base behavior to assert"),
        (f"{PHONE}('995 555 12 34 56')", "the base version timed out"),
    )
    assert not (tmp_path / "out").exists()


def test_other_test_files_are_kept_and_conftest_roots_are_merged(
    tmp_path: Path,
) -> None:
    write_module(tmp_path, "def normalize_phone(text):\n    return text\n")
    folder = tmp_path / ".didibreak" / "tests"
    folder.mkdir(parents=True)
    (folder / "test_other.py").write_text("# kept\n")
    (folder / "conftest.py").write_text(render_conftest(["../../lib"]))

    write_tests(
        tmp_path, tmp_path / ".didibreak", [finding(text_value("x"))], "0.1.0", "a"
    )

    assert (folder / "test_other.py").read_text() == "# kept\n"
    roots = conftest_roots((folder / "conftest.py").read_text())
    assert roots == ("../..", "../../lib")


def test_nested_values_that_stay_equal_also_compare_the_repr() -> None:
    before = Outcome(
        "return", "builtins.list", "[1]", {"type": "list", "items": [_int(1)]}
    )
    after = Outcome(
        "return", "builtins.list", "[True]", {"type": "list", "items": [_bool()]}
    )

    assert "assert repr(result) == '[1]'" in render(finding(before, after))


def _int(number: int) -> dict[str, object]:
    return {"type": "int", "value": number}


def _bool() -> dict[str, object]:
    return {"type": "bool", "value": True}
